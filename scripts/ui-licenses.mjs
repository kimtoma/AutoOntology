#!/usr/bin/env node
// SPDX-License-Identifier: MIT
//
// Regenerates docs/licenses/ui-bundle.md from ui/node_modules.
//
// The package set is the runtime dependency closure of ui/package.json: every entry of
// "dependencies" except the build-only tools in BUILD_ONLY, followed through each
// package's dependencies, optionalDependencies and required peerDependencies. Type-only
// packages (@types/*) are skipped. Run `pnpm install --frozen-lockfile` in ui/ first.
//
//   node scripts/ui-licenses.mjs           write docs/licenses/ui-bundle.md
//   node scripts/ui-licenses.mjs --check   exit 1 if the file is out of date

import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, parse, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const UI = join(ROOT, "ui");
const OUT = join(ROOT, "docs", "licenses", "ui-bundle.md");
// Vite plugins and CSS tooling listed under "dependencies" that do not end up in the bundle.
const BUILD_ONLY = new Set(["tailwindcss", "@tailwindcss/vite"]);
const LICENCE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;
const LICENCE_FILE_LOOSE = /^(licen[cs]e|copying)([-._].*)?$/i;

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

function resolvePackage(name, fromDir) {
  // Node-style lookup: <dir>/node_modules/<name>, walking up from the requiring package.
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return realpathSync(candidate);
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function packageRootFor(pkgDir) {
  // In the pnpm store a package's own dependencies are its siblings, so look them up
  // from the node_modules directory that contains the package (scoped or not).
  const parts = pkgDir.split("/");
  const i = parts.lastIndexOf("node_modules");
  return parts.slice(0, i).join("/") || "/";
}

function licenceOf(manifest) {
  const { license, licenses } = manifest;
  if (typeof license === "string") return license;
  if (license && typeof license.type === "string") return license.type;
  if (Array.isArray(licenses)) {
    return licenses.map((l) => (typeof l === "string" ? l : l.type)).join(" OR ");
  }
  return "UNKNOWN";
}

function licenceText(pkgDir) {
  const files = readdirSync(pkgDir).sort();
  const file = files.find((f) => LICENCE_FILE.test(f)) ?? files.find((f) => LICENCE_FILE_LOOSE.test(f));
  if (!file) return null;
  return readFileSync(join(pkgDir, file), "utf8").replace(/\r\n?/g, "\n").replace(/^\n+/, "").trimEnd();
}

function collect() {
  const rootManifest = readJson(join(UI, "package.json"));
  const seen = new Map(); // realpath -> {name, version, licence, text}
  const queue = Object.keys(rootManifest.dependencies ?? {})
    .filter((name) => !BUILD_ONLY.has(name))
    .map((name) => [name, UI, true]);
  while (queue.length) {
    const [name, fromDir, required] = queue.shift();
    if (name.startsWith("@types/")) continue;
    const dir = resolvePackage(name, fromDir);
    if (!dir) {
      if (required) throw new Error(`${name} is not installed; run pnpm install in ui/ first`);
      continue;
    }
    if (seen.has(dir)) continue;
    const manifest = readJson(join(dir, "package.json"));
    seen.set(dir, {
      name: manifest.name,
      version: manifest.version,
      licence: licenceOf(manifest),
      text: licenceText(dir),
    });
    const base = packageRootFor(dir);
    for (const dep of Object.keys(manifest.dependencies ?? {})) queue.push([dep, base, true]);
    for (const dep of Object.keys(manifest.optionalDependencies ?? {})) queue.push([dep, base, false]);
    const optionalPeers = manifest.peerDependenciesMeta ?? {};
    for (const dep of Object.keys(manifest.peerDependencies ?? {})) {
      if (!optionalPeers[dep]?.optional) queue.push([dep, base, true]);
    }
  }
  const cmp = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  return [...seen.values()].sort((a, b) => cmp(a.name, b.name) || cmp(a.version, b.version));
}

function render(packages) {
  const lines = [
    "# Licences of the npm packages in the web UI bundle",
    "",
    "`autoontology/web/static/dist` is a minified build of `ui/`. It contains code from the",
    "npm packages below: the runtime dependencies of `ui/package.json` and everything they",
    "depend on (build-only tools such as tailwindcss are left out). The licence text of each",
    "package follows the table. This file is generated by `scripts/ui-licenses.mjs`; run",
    "`pnpm licenses:generate` in `ui/` whenever `ui/pnpm-lock.yaml` changes.",
    "",
    "The bundle also contains AutoOntology's adapted copies of shadcn/ui component sources",
    "(`ui/src/components/ui/`, MIT, Copyright (c) 2023 shadcn). They are not an npm package, so",
    "they are not in the table; their licence text is in",
    "[`ui/src/components/ui/LICENSE.md`](../../ui/src/components/ui/LICENSE.md).",
    "",
    "| Package | Version | Licence |",
    "|---|---|---|",
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.licence} |`),
    "",
  ];
  for (const p of packages) {
    lines.push(`## ${p.name} ${p.version} (${p.licence})`, "");
    if (p.text === null) {
      lines.push(`The package ships no licence file; its \`package.json\` declares ${p.licence}.`, "");
    } else {
      lines.push("```text", p.text, "```", "");
    }
  }
  return lines.join("\n").replace(/\n+$/, "\n");
}

const output = render(collect());
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== output) {
    console.error(`${parse(OUT).base} is out of date; run node scripts/ui-licenses.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT}`);
}
